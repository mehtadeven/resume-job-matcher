"""
Generate the browser demo's data file.

Writes web/matcher-data.js with the two stop-word lists matcher.py uses
(scikit-learn's English list + the custom STOP_WORDS in matcher.py) and
the sample resume / job description, so the browser version gives the
same answers as the Python version. Run it again whenever matcher.py's
STOP_WORDS or the sample files change:

    python gen_web_data.py
"""

import json
from pathlib import Path

from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

from matcher import STOP_WORDS

HERE = Path(__file__).parent
OUT_FILE = HERE / "web" / "matcher-data.js"


def main() -> None:
    data = {
        "SKLEARN_STOP_WORDS": sorted(ENGLISH_STOP_WORDS),
        "CUSTOM_STOP_WORDS": sorted(STOP_WORDS),
        "SAMPLE_RESUME": (HERE / "sample_resume.txt").read_text(encoding="utf-8"),
        "SAMPLE_JOB": (HERE / "sample_job.txt").read_text(encoding="utf-8"),
    }
    OUT_FILE.parent.mkdir(exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as file:
        file.write("// Generated by gen_web_data.py - do not edit by hand.\n")
        for name, value in data.items():
            file.write(f"const {name} = {json.dumps(value, ensure_ascii=False)};\n")
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
